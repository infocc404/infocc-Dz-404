-- i 404 internal notifications + owner-only activity log
-- Apply ONCE in Supabase SQL Editor for the EXISTING project. Does not delete existing data.
create table if not exists public.user_notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  body text not null default '',
  kind text not null default 'general',
  link text,
  created_at timestamptz not null default now(),
  read_at timestamptz,
  constraint user_notifications_kind_check check (kind in ('general','announcement','file','request','system'))
);
create index if not exists user_notifications_user_created_idx on public.user_notifications(user_id, created_at desc);
create index if not exists user_notifications_unread_idx on public.user_notifications(user_id) where read_at is null;
alter table public.user_notifications enable row level security;
drop policy if exists "Users read own notifications" on public.user_notifications;
create policy "Users read own notifications" on public.user_notifications for select to authenticated using (user_id = auth.uid());
drop policy if exists "Users update own notifications" on public.user_notifications;
create policy "Users update own notifications" on public.user_notifications for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
drop policy if exists "Users delete own notifications" on public.user_notifications;
create policy "Users delete own notifications" on public.user_notifications for delete to authenticated using (user_id = auth.uid());
grant select, update, delete on public.user_notifications to authenticated;
-- Clients can only read, mark read, or delete their own notifications; inserts remain restricted to trusted database triggers.

create table if not exists public.notification_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  announcements_enabled boolean not null default true,
  new_files_enabled boolean not null default true,
  requests_enabled boolean not null default true,
  updated_at timestamptz not null default now()
);
alter table public.notification_preferences enable row level security;
drop policy if exists "Users read own notification preferences" on public.notification_preferences;
create policy "Users read own notification preferences" on public.notification_preferences for select to authenticated using (user_id = auth.uid());
drop policy if exists "Users manage own notification preferences" on public.notification_preferences;
create policy "Users manage own notification preferences" on public.notification_preferences for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

create table if not exists public.admin_activity_log (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  action text not null,
  target_user_id uuid references auth.users(id) on delete set null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
alter table public.admin_activity_log enable row level security;
-- The app intentionally does not expose this log to ordinary users. Owner-only read policy depends on existing current_role() helper.
drop policy if exists "Owner reads admin activity log" on public.admin_activity_log;
create policy "Owner reads admin activity log" on public.admin_activity_log for select to authenticated using (coalesce(public.current_role(), '') = 'owner');

-- Notify all existing auth users when an announcement is published.
-- Trigger is created only if the announcements table and expected columns exist.
do $$ begin
  if to_regclass('public.announcements') is not null then
    execute $trg$
      create or replace function public.notify_announcement_created()
      returns trigger language plpgsql security definer set search_path = public, auth as $fn$
      begin
        insert into public.user_notifications(user_id, title, body, kind, link)
        select u.id,
               case when coalesce(new.priority, 'normal') = 'urgent' then 'إعلان عاجل جديد'
                    when coalesce(new.priority, 'normal') = 'important' then 'إعلان مهم جديد'
                    else 'إعلان جديد' end,
               coalesce(new.title, 'إعلان') || case when coalesce(new.body, '') = '' then '' else E'\n' || left(new.body, 500) end,
               'announcement', '#/announcements'
        from auth.users u
        where not exists (
          select 1 from public.notification_preferences p
          where p.user_id = u.id and p.announcements_enabled = false
        );
        return new;
      end $fn$;
    $trg$;
    execute 'drop trigger if exists trg_notify_announcement_created on public.announcements';
    execute 'create trigger trg_notify_announcement_created after insert on public.announcements for each row execute function public.notify_announcement_created()';
  end if;
end $$;
