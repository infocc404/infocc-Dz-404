-- Student display-name approval workflow
create table if not exists public.student_name_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  student_email text,
  requested_name text not null check (char_length(btrim(requested_name)) between 2 and 40),
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  owner_note text,
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users(id),
  constraint student_name_requests_review_state check (
    (status = 'pending' and reviewed_at is null and reviewed_by is null)
    or (status in ('approved','rejected') and reviewed_at is not null and reviewed_by is not null)
  )
);
create unique index if not exists student_name_requests_one_pending_per_user
  on public.student_name_requests(user_id) where status = 'pending';
alter table public.student_name_requests enable row level security;
grant select, insert on public.student_name_requests to authenticated;
grant usage, select on sequence public.student_name_requests_id_seq to authenticated;
drop policy if exists student_name_requests_read_own_or_owner on public.student_name_requests;
create policy student_name_requests_read_own_or_owner
  on public.student_name_requests for select to authenticated
  using (user_id = (select auth.uid()) or public.current_role() = 'owner');
drop policy if exists student_name_requests_insert_own on public.student_name_requests;
create policy student_name_requests_insert_own
  on public.student_name_requests for insert to authenticated
  with check (
    user_id = (select auth.uid())
    and status = 'pending'
    and reviewed_by is null
    and reviewed_at is null
    and char_length(btrim(requested_name)) between 2 and 40
  );

create or replace function public.owner_review_student_name_request(
  p_request_id bigint,
  p_approved boolean,
  p_note text default null
) returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_request public.student_name_requests%rowtype;
begin
  if auth.uid() is null or public.current_role() <> 'owner' then
    raise exception 'Only the platform owner can review student name requests';
  end if;
  select * into v_request
  from public.student_name_requests
  where id = p_request_id
  for update;
  if not found then raise exception 'Name request not found'; end if;
  if v_request.status <> 'pending' then raise exception 'This request has already been reviewed'; end if;
  if p_approved then
    update public.student_profiles
       set display_name = v_request.requested_name,
           updated_at = now()
     where user_id = v_request.user_id;
    if not found then raise exception 'Student profile not found'; end if;
  end if;
  update public.student_name_requests
     set status = case when p_approved then 'approved' else 'rejected' end,
         owner_note = nullif(left(coalesce(p_note,''),1000),''),
         reviewed_at = now(),
         reviewed_by = auth.uid()
   where id = p_request_id;
end;
$$;
revoke all on function public.owner_review_student_name_request(bigint, boolean, text) from public, anon;
grant execute on function public.owner_review_student_name_request(bigint, boolean, text) to authenticated;
