-- info cc 404: student account deletion requests and scoped student messaging
-- Additive migration: preserves existing accounts, files, profiles and roles.
begin;

create table if not exists public.account_deletion_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  student_email text,
  reason text,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  owner_note text,
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users(id) on delete set null
);
create index if not exists account_deletion_requests_status_created_idx
  on public.account_deletion_requests(status, created_at desc);
create unique index if not exists one_pending_account_deletion_request_per_student
  on public.account_deletion_requests(user_id) where status = 'pending';
alter table public.account_deletion_requests enable row level security;
drop policy if exists "students create own deletion requests" on public.account_deletion_requests;
drop policy if exists "students read own deletion requests" on public.account_deletion_requests;
drop policy if exists "owner manages deletion requests" on public.account_deletion_requests;
create policy "students create own deletion requests" on public.account_deletion_requests
  for insert to authenticated with check (user_id = auth.uid() and status = 'pending');
create policy "students read own deletion requests" on public.account_deletion_requests
  for select to authenticated using (user_id = auth.uid());
create policy "owner manages deletion requests" on public.account_deletion_requests
  for all to authenticated using (public.current_role() = 'owner')
  with check (public.current_role() = 'owner');

create or replace function public.prepare_account_deletion_request()
returns trigger language plpgsql security definer
set search_path = pg_catalog, public, auth, pg_temp as $$
declare
  v_email text;
begin
  if auth.uid() is null or public.current_role() <> 'student' then
    raise exception 'Only students may request account deletion';
  end if;
  if new.user_id is not null and new.user_id <> auth.uid() then
    raise exception 'You may only request deletion of your own account';
  end if;
  select email into v_email from auth.users where id = auth.uid();
  new.user_id := auth.uid();
  new.student_email := v_email;
  new.status := 'pending';
  new.owner_note := null;
  new.reviewed_at := null;
  new.reviewed_by := null;
  new.created_at := now();
  return new;
end; $$;
drop trigger if exists trg_prepare_account_deletion_request on public.account_deletion_requests;
create trigger trg_prepare_account_deletion_request before insert on public.account_deletion_requests
for each row execute function public.prepare_account_deletion_request();

create table if not exists public.student_conversations (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references auth.users(id) on delete cascade,
  group_no smallint not null check (group_no between 1 and 10),
  subject text not null check (char_length(trim(subject)) between 2 and 160),
  created_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists student_conversations_student_updated_idx
  on public.student_conversations(student_id, updated_at desc);
create table if not exists public.student_messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.student_conversations(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(trim(body)) between 1 and 5000),
  created_at timestamptz not null default now(),
  read_at timestamptz
);
create index if not exists student_messages_conversation_created_idx
  on public.student_messages(conversation_id, created_at);
alter table public.student_conversations enable row level security;
alter table public.student_messages enable row level security;

-- Allow each uploader/supervisor to see only the student directory for their assigned group.
drop policy if exists "uploaders read students in assigned group" on public.student_profiles;
create policy "uploaders read students in assigned group" on public.student_profiles
  for select to authenticated using (
    public.current_role() = 'uploader'
    and exists (select 1 from public.uploaders up
      where up.user_id = auth.uid() and up.group_no = student_profiles.group_no)
  );

create or replace function public.can_access_student_conversation(p_conversation uuid)
returns boolean language sql stable security definer
set search_path = pg_catalog, public, auth, pg_temp as $$
  select exists (
    select 1 from public.student_conversations c
    left join public.student_profiles sp on sp.user_id = c.student_id
    left join public.uploaders up on up.user_id = auth.uid()
    where c.id = p_conversation and (
      public.current_role() = 'owner'
      or c.student_id = auth.uid()
      or (public.current_role() = 'uploader' and up.group_no = sp.group_no)
    )
  );
$$;
revoke all on function public.can_access_student_conversation(uuid) from public, anon;
grant execute on function public.can_access_student_conversation(uuid) to authenticated;

drop policy if exists "conversation participants read" on public.student_conversations;
drop policy if exists "authorized staff create conversations" on public.student_conversations;
drop policy if exists "conversation participants update" on public.student_conversations;
create policy "conversation participants read" on public.student_conversations
  for select to authenticated using (
    public.current_role() = 'owner'
    or student_id = auth.uid()
    or (public.current_role() = 'uploader' and exists (
      select 1 from public.student_profiles sp
      join public.uploaders up on up.user_id = auth.uid()
      where sp.user_id = student_conversations.student_id and sp.group_no = up.group_no
    ))
  );
create policy "authorized staff create conversations" on public.student_conversations
  for insert to authenticated with check (
    created_by = auth.uid()
    and exists (select 1 from public.student_profiles sp
      where sp.user_id = student_conversations.student_id
        and sp.group_no = student_conversations.group_no)
    and (
      public.current_role() = 'owner'
      or (public.current_role() = 'uploader' and exists (
        select 1 from public.uploaders up
        where up.user_id = auth.uid() and up.group_no = student_conversations.group_no
      ))
    )
  );
create policy "conversation participants update" on public.student_conversations
  for update to authenticated using (
    public.current_role() = 'owner' or student_id = auth.uid()
    or (public.current_role() = 'uploader' and exists (
      select 1 from public.student_profiles sp join public.uploaders up on up.user_id = auth.uid()
      where sp.user_id = student_conversations.student_id and sp.group_no = up.group_no
    ))
  ) with check (public.current_role() = 'owner' or student_id = auth.uid()
    or (public.current_role() = 'uploader' and exists (
      select 1 from public.student_profiles sp join public.uploaders up on up.user_id = auth.uid()
      where sp.user_id = student_conversations.student_id and sp.group_no = up.group_no
    )));

drop policy if exists "conversation messages read" on public.student_messages;
drop policy if exists "conversation messages send" on public.student_messages;
drop policy if exists "conversation messages update read" on public.student_messages;
create policy "conversation messages read" on public.student_messages
  for select to authenticated using (public.can_access_student_conversation(conversation_id));
create policy "conversation messages send" on public.student_messages
  for insert to authenticated with check (
    sender_id = auth.uid() and char_length(trim(body)) between 1 and 5000
    and public.can_access_student_conversation(conversation_id)
  );
create policy "conversation messages update read" on public.student_messages
  for update to authenticated using (public.can_access_student_conversation(conversation_id))
  with check (public.can_access_student_conversation(conversation_id));

-- Students may only reply in an existing conversation; they cannot open staff-to-student threads.
create or replace function public.guard_student_message_insert()
returns trigger language plpgsql security definer
set search_path = pg_catalog, public, auth, pg_temp as $$
declare v_student uuid; v_group smallint; v_role text;
begin
  select student_id, group_no into v_student, v_group
  from public.student_conversations where id = new.conversation_id;
  v_role := public.current_role();
  if v_role = 'student' then
    if v_student <> auth.uid() then raise exception 'Students may only reply to their own conversations'; end if;
  elsif v_role = 'uploader' then
    if not exists (select 1 from public.uploaders up where up.user_id = auth.uid() and up.group_no = v_group)
      then raise exception 'You may only message students in your assigned group'; end if;
  elsif v_role <> 'owner' then
    raise exception 'This role cannot use student messaging';
  end if;
  new.sender_id := auth.uid();
  return new;
end; $$;
drop trigger if exists trg_guard_student_message_insert on public.student_messages;
create trigger trg_guard_student_message_insert before insert on public.student_messages
for each row execute function public.guard_student_message_insert();

create or replace function public.touch_student_conversation()
returns trigger language plpgsql security definer
set search_path = pg_catalog, public, pg_temp as $$
begin
  update public.student_conversations set updated_at = now() where id = new.conversation_id;
  return new;
end; $$;
drop trigger if exists trg_touch_student_conversation on public.student_messages;
create trigger trg_touch_student_conversation after insert on public.student_messages
for each row execute function public.touch_student_conversation();

commit;
notify pgrst, 'reload schema';
