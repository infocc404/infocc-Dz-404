-- Group and general chat for info cc 404.
-- Additive only: preserves the existing private student conversations and messages.
begin;

create table if not exists public.student_group_chat_messages (
  id bigint generated by default as identity primary key,
  chat_type text not null check (chat_type in ('general','group')),
  group_no smallint,
  sender_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(btrim(body)) between 1 and 3000),
  created_at timestamptz not null default now(),
  constraint student_group_chat_scope_check check (
    (chat_type = 'general' and group_no is null)
    or (chat_type = 'group' and group_no between 1 and 10)
  )
);
create index if not exists student_group_chat_scope_created_idx
  on public.student_group_chat_messages(chat_type, group_no, created_at desc);
alter table public.student_group_chat_messages enable row level security;
grant select, insert on public.student_group_chat_messages to authenticated;

create or replace function public.can_access_student_group_chat(p_chat_type text, p_group_no integer)
returns boolean
language sql stable security definer
set search_path = pg_catalog, public, auth, pg_temp
as $$
  select auth.uid() is not null and (
    (p_chat_type = 'general' and public.current_role() in ('student','owner','admin','uploader'))
    or (
      p_chat_type = 'group'
      and p_group_no between 1 and 10
      and (
        public.current_role() in ('owner','admin')
        or (public.current_role() = 'student' and exists (
          select 1 from public.student_profiles sp
          where sp.user_id = auth.uid() and sp.group_no = p_group_no
        ))
        or (public.current_role() = 'uploader' and exists (
          select 1 from public.uploaders up
          where up.user_id = auth.uid() and up.group_no = p_group_no
        ))
      )
    )
  );
$$;
revoke all on function public.can_access_student_group_chat(text, smallint) from public, anon;
grant execute on function public.can_access_student_group_chat(text, smallint) to authenticated;

drop policy if exists student_group_chat_read_scope on public.student_group_chat_messages;
create policy student_group_chat_read_scope
on public.student_group_chat_messages for select to authenticated
using (public.can_access_student_group_chat(chat_type, group_no));

drop policy if exists student_group_chat_insert_scope on public.student_group_chat_messages;
create policy student_group_chat_insert_scope
on public.student_group_chat_messages for insert to authenticated
with check (
  sender_id = auth.uid()
  and char_length(btrim(body)) between 1 and 3000
  and public.can_access_student_group_chat(chat_type, group_no)
);

create or replace function public.get_student_group_chat_messages(
  p_chat_type text,
  p_group_no integer default null
)
returns table (
  id bigint,
  sender_id uuid,
  sender_name text,
  body text,
  created_at timestamptz
)
language plpgsql stable security definer
set search_path = pg_catalog, public, auth, pg_temp
as $$
begin
  if not public.can_access_student_group_chat(p_chat_type, p_group_no) then
    raise exception 'ليس لديك إذن لدخول هذه المحادثة';
  end if;
  return query
    select m.id, m.sender_id,
      coalesce(nullif(btrim(sp.display_name), ''),
        case when m.sender_id = auth.uid() then 'أنت'
             when public.current_role() in ('owner','admin','uploader') then 'الإدارة'
             else 'عضو' end)::text,
      m.body, m.created_at
    from public.student_group_chat_messages m
    left join public.student_profiles sp on sp.user_id = m.sender_id
    where m.chat_type = p_chat_type
      and m.group_no is not distinct from p_group_no
    order by m.created_at asc
    limit 150;
end;
$$;
revoke all on function public.get_student_group_chat_messages(text, smallint) from public, anon;
grant execute on function public.get_student_group_chat_messages(text, smallint) to authenticated;

create or replace function public.send_student_group_chat_message(
  p_chat_type text,
  p_group_no integer,
  p_body text
)
returns bigint
language plpgsql security definer
set search_path = pg_catalog, public, auth, pg_temp
as $$
declare
  v_id bigint;
  v_body text := btrim(coalesce(p_body, ''));
begin
  if auth.uid() is null then raise exception 'يجب تسجيل الدخول أولا'; end if;
  if char_length(v_body) < 1 or char_length(v_body) > 3000 then
    raise exception 'الرسالة يجب أن تكون بين حرف واحد و3000 حرف';
  end if;
  if not public.can_access_student_group_chat(p_chat_type, p_group_no) then
    raise exception 'ليس لديك إذن للإرسال في هذه المحادثة';
  end if;
  insert into public.student_group_chat_messages(chat_type, group_no, sender_id, body)
  values (p_chat_type, case when p_chat_type = 'general' then null else p_group_no end, auth.uid(), v_body)
  returning id into v_id;
  return v_id;
end;
$$;
revoke all on function public.send_student_group_chat_message(text, smallint, text) from public, anon;
grant execute on function public.send_student_group_chat_message(text, smallint, text) to authenticated;

commit;
notify pgrst, 'reload schema';


-- Follow-up authorization/display correction:
-- Owners and admins are global roles, not members of a student group.
create or replace function public.my_role()
returns table(user_role text, uploader_group smallint, assigned_group smallint)
language plpgsql stable security definer
set search_path = pg_catalog, public, auth, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_role text;
  v_uploader_group smallint;
  v_assigned_group smallint;
begin
  if v_uid is null then
    return query select 'anon'::text, null::smallint, null::smallint;
    return;
  end if;
  v_role := public.current_role();
  if v_role = 'suspended' then
    return query select 'suspended'::text, null::smallint, null::smallint;
    return;
  end if;
  if v_role = 'uploader' then
    select up.group_no into v_uploader_group from public.uploaders up where up.user_id = v_uid;
  elsif v_role = 'student' then
    v_assigned_group := public.my_group_no();
  end if;
  return query select v_role, v_uploader_group, v_assigned_group;
end;
$$;

drop function if exists public.get_student_group_chat_messages(text, integer);
create function public.get_student_group_chat_messages(
  p_chat_type text,
  p_group_no integer default null
)
returns table (
  id bigint,
  sender_id uuid,
  sender_name text,
  sender_role text,
  body text,
  created_at timestamptz
)
language plpgsql stable security definer
set search_path = pg_catalog, public, auth, pg_temp
as $$
begin
  if not public.can_access_student_group_chat(p_chat_type, p_group_no) then
    raise exception 'ليس لديك إذن لدخول هذه المحادثة';
  end if;
  return query
    select
      m.id,
      m.sender_id,
      coalesce(
        nullif(btrim(sp.display_name), ''),
        case
          when m.sender_id = auth.uid() then 'أنت'
          when lower(coalesce(u.email, '')) = 'locoviber16@gmail.com' then 'المالك'
          when exists (select 1 from public.admins a where a.user_id = m.sender_id) then 'الإدارة'
          when exists (select 1 from public.uploaders up where up.user_id = m.sender_id) then 'رئيس القسم'
          else 'طالب'
        end
      )::text,
      case
        when lower(coalesce(u.email, '')) = 'locoviber16@gmail.com' then 'owner'
        when exists (select 1 from public.admins a where a.user_id = m.sender_id) then 'admin'
        when exists (select 1 from public.uploaders up where up.user_id = m.sender_id) then 'uploader'
        else 'student'
      end::text,
      m.body,
      m.created_at
    from public.student_group_chat_messages m
    left join public.student_profiles sp on sp.user_id = m.sender_id
    left join auth.users u on u.id = m.sender_id
    where m.chat_type = p_chat_type
      and m.group_no is not distinct from p_group_no
    order by m.created_at asc
    limit 150;
end;
$$;
revoke all on function public.get_student_group_chat_messages(text, integer) from public, anon;
grant execute on function public.get_student_group_chat_messages(text, integer) to authenticated;
notify pgrst, 'reload schema';
