-- info cc 404: secure student group assignment/change requests
-- Run once in Supabase Dashboard > SQL Editor > New query > Run.
-- This migration is additive: it does not delete users, files, or existing profile assignments.

begin;

create table if not exists public.group_change_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  student_email text,
  current_group smallint check (current_group is null or current_group between 1 and 10),
  requested_group smallint not null check (requested_group between 1 and 10),
  reason text not null check (char_length(trim(reason)) between 5 and 1000),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  admin_note text,
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists idx_group_change_requests_user_created
  on public.group_change_requests(user_id, created_at desc);
create index if not exists idx_group_change_requests_pending
  on public.group_change_requests(status, created_at) where status = 'pending';
create unique index if not exists idx_one_pending_group_request_per_user
  on public.group_change_requests(user_id) where status = 'pending';

alter table public.group_change_requests enable row level security;

-- Remove old policies with these names before recreating them safely.
drop policy if exists "students read own group change requests" on public.group_change_requests;
drop policy if exists "admins read all group change requests" on public.group_change_requests;
drop policy if exists "students submit own group change requests" on public.group_change_requests;

create policy "students read own group change requests"
  on public.group_change_requests for select to authenticated
  using (user_id = auth.uid());

create policy "admins read all group change requests"
  on public.group_change_requests for select to authenticated
  using (public.current_role() in ('admin', 'owner'));

create policy "students submit own group change requests"
  on public.group_change_requests for insert to authenticated
  with check (user_id = auth.uid() and status = 'pending');

-- Set trusted fields from the authenticated session/database, not from the browser payload.
create or replace function public.prepare_group_change_request()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, auth, pg_temp
as $$
declare
  v_email text;
  v_group smallint;
begin
  if auth.uid() is null or (new.user_id is not null and new.user_id is distinct from auth.uid()) then
    raise exception 'You may only submit a request for your own account';
  end if;

  select u.email into v_email from auth.users u where u.id = auth.uid();
  select sp.group_no into v_group from public.student_profiles sp where sp.user_id = auth.uid();

  new.user_id := auth.uid();
  new.student_email := v_email;
  new.current_group := v_group;
  new.status := 'pending';
  new.admin_note := null;
  new.reviewed_by := null;
  new.reviewed_at := null;
  new.created_at := now();
  new.reason := trim(new.reason);

  if new.requested_group = v_group then
    raise exception 'The requested group is already assigned to your account';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_prepare_group_change_request on public.group_change_requests;
create trigger trg_prepare_group_change_request
  before insert on public.group_change_requests
  for each row execute function public.prepare_group_change_request();

-- Only the owner or explicitly authorized admins may review a request.
-- Approval and profile assignment happen in one transaction.
create or replace function public.review_group_change_request(
  p_request_id bigint,
  p_approve boolean,
  p_admin_note text default null
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public, auth, pg_temp
as $$
declare
  v_request public.group_change_requests%rowtype;
  v_uid uuid := auth.uid();
begin
  if v_uid is null or public.current_role() not in ('owner', 'admin') then
    raise exception 'Only the owner or an authorized administrator can review group requests';
  end if;

  select * into v_request
  from public.group_change_requests
  where id = p_request_id
  for update;

  if not found then
    raise exception 'Group change request not found';
  end if;
  if v_request.status <> 'pending' then
    raise exception 'This request has already been reviewed';
  end if;

  if p_approve then
    insert into public.student_profiles(user_id, group_no)
    values (v_request.user_id, v_request.requested_group)
    on conflict (user_id) do update set group_no = excluded.group_no;

    update public.group_change_requests
    set status = 'approved',
        admin_note = nullif(left(trim(coalesce(p_admin_note, '')), 1000), ''),
        reviewed_by = v_uid,
        reviewed_at = now()
    where id = p_request_id;
  else
    update public.group_change_requests
    set status = 'rejected',
        admin_note = nullif(left(trim(coalesce(p_admin_note, '')), 1000), ''),
        reviewed_by = v_uid,
        reviewed_at = now()
    where id = p_request_id;
  end if;
end;
$$;

revoke all on function public.prepare_group_change_request() from public, anon, authenticated;
revoke all on function public.review_group_change_request(bigint, boolean, text) from public, anon;
grant execute on function public.review_group_change_request(bigint, boolean, text) to authenticated;
grant select, insert on public.group_change_requests to authenticated;

commit;
